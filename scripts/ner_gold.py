# The two halves of the layer were built separately and name a few concepts
# differently. Collapsing those pairs keeps the score about extraction rather
# than about vocabulary bookkeeping.
NORM = {
    "нарушение дыхания": "удушье",
    "кровь": "кровотечение",
    "обморок": "потеря сознания",
    "нарушение сна": "бессонница",
    "ноющая боль": "боль",
    "щемящая боль": "боль",
}


def norm(items):
    return {NORM.get(x, x) for x in items}


def score(gold_sets, pred_sets):
    """Micro precision / recall / F1 over a list of (gold, predicted) sets."""
    tp = sum(len(g & p) for g, p in zip(gold_sets, pred_sets))
    fp = sum(len(p - g) for g, p in zip(gold_sets, pred_sets))
    fn = sum(len(g - p) for g, p in zip(gold_sets, pred_sets))
    prec = tp / (tp + fp) if tp + fp else float("nan")
    rec = tp / (tp + fn) if tp + fn else float("nan")
    f1 = 2 * prec * rec / (prec + rec) if tp else 0.0
    return {"tp": tp, "fp": fp, "fn": fn,
            "precision": round(prec, 3), "recall": round(rec, 3), "f1": round(f1, 3)}


